// ------------------------------------------------------------------ PDF

const escapePdf = (text) => text.replace(/[\\()]/g, (c) => `\\${c}`);

/**
 * A one-page A4 PDF: a header band, a diagonal SAMPLE watermark, then lines of text.
 * `lines` are [size, text, bold?]; an empty text leaves a gap.
 */
function pdf(title, lines, footer = FOOTER) {
  const ops = [
    // Watermark: light grey, turned 35 degrees.
    'q 0.9 g BT /F2 110 Tf 0.819 0.574 -0.574 0.819 120 230 Tm (SAMPLE) Tj ET Q',
    // Header band and its text.
    'q 0.13 0.29 0.53 rg 0 760 595 82 re f Q',
    `q 1 g BT /F2 20 Tf 50 800 Td (${escapePdf(title)}) Tj ET Q`,
    'q 1 g BT /F1 10 Tf 50 778 Td (SAMPLE DOCUMENT - made up for the Pharos files sample. Not a real record.) Tj ET Q',
  ];
  let y = 720;
  for (const [size, text, bold] of lines) {
    if (text)
      ops.push(`BT /${bold ? 'F2' : 'F1'} ${size} Tf 50 ${y} Td (${escapePdf(text)}) Tj ET`);
    y -= size + 9;
  }
  ops.push(`q 0.6 g BT /F1 9 Tf 50 40 Td (${escapePdf(footer)}) Tj ET Q`);
  const stream = ops.join('\n');
  const objects = [
    '<< /Type /Catalog /Pages 2 0 R >>',
    '<< /Type /Pages /Kids [3 0 R] /Count 1 >>',
    '<< /Type /Page /Parent 2 0 R /MediaBox [0 0 595 842] /Resources << /Font << /F1 4 0 R /F2 5 0 R >> >> /Contents 6 0 R >>',
    '<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica /Encoding /WinAnsiEncoding >>',
    '<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica-Bold /Encoding /WinAnsiEncoding >>',
    `<< /Length ${Buffer.byteLength(stream, 'latin1')} >>\nstream\n${stream}\nendstream`,
  ];
  let body = '%PDF-1.4\n';
  const offsets = objects.map((object, i) => {
    const at = Buffer.byteLength(body, 'latin1');
    body += `${i + 1} 0 obj\n${object}\nendobj\n`;
    return at;
  });
  const xref = Buffer.byteLength(body, 'latin1');
  body += `xref\n0 ${objects.length + 1}\n0000000000 65535 f \n`;
  body += offsets.map((o) => `${String(o).padStart(10, '0')} 00000 n \n`).join('');
  body += `trailer\n<< /Size ${objects.length + 1} /Root 1 0 R /Info << /Title (${escapePdf(title)} - SAMPLE) >> >>\nstartxref\n${xref}\n%%EOF\n`;
  return Buffer.from(body, 'latin1');
}

// ------------------------------------------------------------------ PNG

const CRC_TABLE = Array.from({ length: 256 }, (_, n) => {
  let c = n;
  for (let k = 0; k < 8; k++) c = c & 1 ? 0xedb88320 ^ (c >>> 1) : c >>> 1;
  return c >>> 0;
});
function crc32(bytes) {
  let c = 0xffffffff;
  for (const b of bytes) c = CRC_TABLE[(c ^ b) & 0xff] ^ (c >>> 8);
  return (c ^ 0xffffffff) >>> 0;
}
function chunk(type, data) {
  const head = Buffer.alloc(8);
  head.writeUInt32BE(data.length, 0);
  head.write(type, 4, 'latin1');
  const crc = Buffer.alloc(4);
  crc.writeUInt32BE(crc32(Buffer.concat([head.subarray(4), data])), 0);
  return Buffer.concat([head, data, crc]);
}

// 5x7 letters for the stamp's words.
const GLYPHS = {
  S: ['01111', '10000', '10000', '01110', '00001', '00001', '11110'],
  A: ['01110', '10001', '10001', '11111', '10001', '10001', '10001'],
  M: ['10001', '11011', '10101', '10101', '10001', '10001', '10001'],
  P: ['11110', '10001', '10001', '11110', '10000', '10000', '10000'],
  L: ['10000', '10000', '10000', '10000', '10000', '10000', '11111'],
  E: ['11111', '10000', '10000', '11110', '10000', '10000', '11111'],
  X: ['10001', '10001', '01010', '00100', '01010', '10001', '10001'],
  C: ['01111', '10000', '10000', '10000', '10000', '10000', '01111'],
  O: ['01110', '10001', '10001', '10001', '10001', '10001', '01110'],
  ' ': ['00000', '00000', '00000', '00000', '00000', '00000', '00000'],
};

/** A round red company-seal stamp: two rings, "SAMPLE" across and "EXAMPLE CO" below. */
function sealPng(size = 240) {
  const px = new Uint8Array(size * size * 4); // transparent
  const ink = [190, 30, 45, 255];
  const set = (x, y) => {
    if (x < 0 || y < 0 || x >= size || y >= size) return;
    px.set(ink, (y * size + x) * 4);
  };
  const c = (size - 1) / 2;
  for (let y = 0; y < size; y++)
    for (let x = 0; x < size; x++) {
      const r = Math.hypot(x - c, y - c);
      if ((r >= 104 && r <= 116) || (r >= 92 && r <= 96)) set(x, y);
    }
  const word = (text, scale, top) => {
    const width = text.length * 6 * scale - scale;
    const left = Math.round(c - width / 2);
    [...text].forEach((ch, i) =>
      GLYPHS[ch].forEach((row, gy) =>
        [...row].forEach((bit, gx) => {
          if (bit !== '1') return;
          for (let dy = 0; dy < scale; dy++)
            for (let dx = 0; dx < scale; dx++)
              set(left + (i * 6 + gx) * scale + dx, top + gy * scale + dy);
        }),
      ),
    );
  };
  word('SAMPLE', 4, 90);
  word('EXAMPLE CO', 2, 136);
  const raw = Buffer.alloc(size * (size * 4 + 1));
  for (let y = 0; y < size; y++) {
    raw[y * (size * 4 + 1)] = 0; // no filter
    Buffer.from(px.buffer, y * size * 4, size * 4).copy(raw, y * (size * 4 + 1) + 1);
  }
  const header = Buffer.alloc(13);
  header.writeUInt32BE(size, 0);
  header.writeUInt32BE(size, 4);
  header[8] = 8; // bit depth
  header[9] = 6; // RGBA
  return Buffer.concat([
    Buffer.from([0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a]),
    chunk('IHDR', header),
    chunk('tEXt', Buffer.from('Comment\0SAMPLE seal for the fictional Example Co', 'latin1')),
    chunk('IDAT', deflateSync(raw, { level: 9 })),
    chunk('IEND', Buffer.alloc(0)),
  ]);
}

